#!/usr/bin/env bun
// Regenerates src/chat/antigravity/prices.ts, the built-in price table that
// prices Antigravity turns (add-antigravity-chat D11). Chat never fetches
// prices at runtime; this development step does, from models.dev, so each
// run needs approval:
//
//   bun run scripts/update-antigravity-prices.ts                 fetch and write
//   bun run scripts/update-antigravity-prices.ts --input api.json  use a saved copy
//
// Rules:
// - Google's rates as models.dev records them for Vertex AI (the Standard
//   tier at the Global endpoint), including the partner models (Claude,
//   GPT-OSS) agy offers.
// - Base rates only: long-context tiers are not applied, because a turn's
//   usage is not broken down per request.
// - Input, output and cache-read rates are kept; cache writes are not priced.
//   Thinking is inside agy's output count, so it is priced at the output rate.
// - Thinking levels do not change rates: agy's model families are priced.
// - A model with no entry of its own borrows its family's price (FAMILY_MAP).
// The run fails, naming every entry it could not find, rather than writing a
// table that silently prices less than it should.

import path from "node:path";

import type { AntigravityPriceTable, ModelRates } from "../src/chat/antigravity/pricing";

export const MODELS_DEV_URL = "https://models.dev/api.json";

// agy's model families and the models.dev entries that price them. Kept by
// hand: neither side names the other. Correct an id here when models.dev
// files a model under another one.
export const MODELS_DEV_SOURCES: Readonly<Record<string, { provider: string; model: string }>> = {
  "gemini-4-neon": { provider: "google-vertex", model: "gemini-4-neon" },
  "gemini-4-argon": { provider: "google-vertex", model: "gemini-4-argon" },
  "gemini-4-hydrogen": { provider: "google-vertex", model: "gemini-4-hydrogen" },
  "gemini-3.8-flash": { provider: "google-vertex", model: "gemini-3.8-flash" },
  "claude-opus-5-5": { provider: "google-vertex", model: "claude-opus-5-5@default" },
  "claude-sonnet-5-5": { provider: "google-vertex", model: "claude-sonnet-5-5@default" },
  "gpt-oss-120b-medium": { provider: "google-vertex", model: "openai/gpt-oss-120b-maas" },
};

// Models without a models.dev entry of their own, and the family they are priced as.
export const FAMILY_MAP: Readonly<Record<string, string>> = {
  "gemini-pro-orchestrator-neon": "gemini-4-neon",
  // agy names it "Orchestrator (Argon)".
  "gemini-pro-orchestrator-g1-pro": "gemini-4-argon",
};

type ModelsDev = Record<string, { models?: Record<string, { cost?: { input?: unknown; output?: unknown; cache_read?: unknown } }> }>;

const rate = (value: unknown) => typeof value === "number" && Number.isFinite(value) && value >= 0 ? value : undefined;

/** The table for a models.dev snapshot, or an error naming what it lacks. */
export function buildPriceTable(data: unknown, snapshot: string): AntigravityPriceTable {
  const providers = data as ModelsDev;
  const models: AntigravityPriceTable["models"] = {};
  const missing: string[] = [];
  for (const [family, source] of Object.entries(MODELS_DEV_SOURCES)) {
    const cost = providers?.[source.provider]?.models?.[source.model]?.cost;
    const input = rate(cost?.input);
    const output = rate(cost?.output);
    if (input === undefined || output === undefined) {
      missing.push(`${family} (${source.provider}/${source.model})`);
      continue;
    }
    const cacheRead = rate(cost?.cache_read);
    const rates: ModelRates = { input, output, ...(cacheRead !== undefined ? { cacheRead } : {}) };
    models[family] = { ...rates, from: `${source.provider}/${source.model}` };
  }
  for (const [model, family] of Object.entries(FAMILY_MAP)) {
    if (!models[family] && !missing.some(entry => entry.startsWith(`${family} `))) missing.push(`${model} (family ${family})`);
  }
  if (missing.length) throw new Error(`models.dev has no base input and output rate for: ${missing.join(", ")}. Correct MODELS_DEV_SOURCES in scripts/update-antigravity-prices.ts.`);
  return { source: MODELS_DEV_URL, snapshot, models, families: { ...FAMILY_MAP } };
}

export function renderPriceTable(table: AntigravityPriceTable): string {
  return `// Generated by scripts/update-antigravity-prices.ts. Do not edit by hand.
// Source: ${table.source}
// Snapshot: ${table.snapshot ?? "none yet: run the script (it fetches models.dev, so it needs approval)"}
// USD per million tokens. Base rates only; cache writes are unpriced.

import type { AntigravityPriceTable } from "./pricing";

export const ANTIGRAVITY_PRICES: AntigravityPriceTable = ${JSON.stringify(table, null, 2)};
`;
}

async function main(argv: string[]): Promise<void> {
  const inputIndex = argv.indexOf("--input");
  const data = inputIndex >= 0
    ? JSON.parse(await Bun.file(argv[inputIndex + 1]!).text())
    : await fetch(MODELS_DEV_URL).then(response => {
      if (!response.ok) throw new Error(`${MODELS_DEV_URL} answered ${response.status}`);
      return response.json();
    });
  const table = buildPriceTable(data, new Date().toISOString().slice(0, 10));
  const target = path.join(import.meta.dir, "../src/chat/antigravity/prices.ts");
  await Bun.write(target, renderPriceTable(table));
  console.log(`wrote ${path.relative(process.cwd(), target)}: ${Object.keys(table.models).length} models, snapshot ${table.snapshot}`);
}

if (import.meta.main) await main(process.argv.slice(2));
