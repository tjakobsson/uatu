import type { DocumentMeta } from "../shared/types";
import { fileKey, RecentModel, relativeWriteAge } from "./recent-model";
import { mediaKind } from "../shared/media";

const ROW_HEIGHT = 56;
const OVERSCAN = 4;

export class RecentView {
  private entries: readonly DocumentMeta[] = [];
  private selectedId: string | null = null;
  private pressed = false;
  private pressGeneration = 0;
  private pending: (() => void) | null = null;
  private focusedKey: string | null = null;
  private focusedAction: "open" | "play" = "open";
  private playingKey: string | null = null;
  private readonly content = document.createElement("div");
  private readonly observer: ResizeObserver;
  private readonly timer: ReturnType<typeof setInterval>;
  private readonly release = () => {
    if (!this.pressed) return;
    const generation = this.pressGeneration;
    // Native click follows pointerup. Keep the mapping until that click has
    // completed, including compatibility clicks generated by touch browsers.
    setTimeout(() => {
      if (generation !== this.pressGeneration) return;
      this.pressed = false; const pending = this.pending; this.pending = null; if (pending) pending(); else this.render();
    }, 0);
  };

  constructor(private readonly container: HTMLElement, private readonly model: RecentModel,
    private readonly onSelect: (id: string) => void, private readonly onPlay?: (doc: DocumentMeta) => void) {
    container.append(this.content);
    container.setAttribute("role", "list");
    container.setAttribute("aria-label", "Recent files");
    container.tabIndex = 0;
    container.addEventListener("scroll", () => { if (!this.pressed) this.render(); });
    container.addEventListener("pointerdown", () => { this.pressed = true; this.pressGeneration++; });
    window.addEventListener("pointerup", this.release);
    window.addEventListener("pointercancel", this.release);
    window.addEventListener("blur", this.release);
    container.addEventListener("keydown", event => this.keydown(event));
    this.observer = new ResizeObserver(() => { if (!this.pressed) this.render(); });
    this.observer.observe(container);
    this.timer = setInterval(() => { if (!container.hidden) this.refreshAges(); }, 30_000);
  }

  getDocuments(): readonly DocumentMeta[] { return this.entries; }

  setPlayingFile(key: string | null): void {
    this.playingKey = key;
    for (const row of this.content.children) {
      const indicator = row.querySelector<HTMLElement>(".recent-file-playing");
      if (indicator) indicator.hidden = row.querySelector<HTMLButtonElement>(".recent-file-open")!.dataset.fileKey !== key;
    }
  }

  private syncRowActions(row: HTMLElement, doc: DocumentMeta): void {
    const open = row.querySelector<HTMLButtonElement>(".recent-file-open")!;
    let indicator = row.querySelector<HTMLElement>(".recent-file-playing");
    if (!indicator) {
      indicator = document.createElement("span"); indicator.className = "recent-file-playing";
      indicator.setAttribute("role", "img"); indicator.setAttribute("aria-label", "Playing");
      indicator.title = "Playing"; indicator.textContent = "▶"; open.append(indicator);
    }
    indicator.hidden = fileKey(doc) !== this.playingKey;
    let play = row.querySelector<HTMLButtonElement>(".recent-file-play");
    if (!this.onPlay || !mediaKind(doc.name)) { play?.remove(); return; }
    if (!play) {
      play = document.createElement("button"); play.type = "button"; play.className = "recent-file-play"; play.textContent = "▶";
      play.addEventListener("focus", () => { this.focusedKey = fileKey(doc); this.focusedAction = "play"; });
      play.addEventListener("click", () => {
        const current = this.model.get(fileKey(doc));
        if (current && this.entries.some(entry => fileKey(entry) === fileKey(current))) this.onPlay?.(current);
      });
      row.append(play);
    }
    play.setAttribute("aria-label", `Play ${this.model.searchPath(doc)}`);
    play.title = `Play ${doc.name}`;
    play.tabIndex = this.focusedKey ? (this.focusedKey === fileKey(doc) ? 0 : -1) : (this.entries[0] === doc ? 0 : -1);
  }

  update(entries: readonly DocumentMeta[], selectedId: string | null): void {
    // Copy the array because the incremental model mutates its ordering.
    const next = [...entries];
    const reconcile = () => {
      const top = Math.floor(this.container.scrollTop / ROW_HEIGHT);
      const offset = this.container.scrollTop % ROW_HEIGHT;
      const anchors = this.entries.slice(top);
      const hadFocus = this.container.contains(document.activeElement);
      const focusedIndex = this.entries.findIndex(doc => fileKey(doc) === this.focusedKey);
      this.entries = next;
      this.selectedId = selectedId;
      this.content.style.height = `${next.length * ROW_HEIGHT}px`;
      if (this.container.scrollTop > 0) {
        const positions = new Map(next.map((doc, index) => [fileKey(doc), index]));
        const anchor = anchors.find(doc => {
          const position = positions.get(fileKey(doc));
          return position !== undefined && next[position]!.mtimeMs === doc.mtimeMs;
        }) ?? anchors.find(doc => positions.has(fileKey(doc)));
        if (anchor) this.container.scrollTop = Math.max(0, (positions.get(fileKey(anchor))! - anchors.indexOf(anchor)) * ROW_HEIGHT + offset);
      }
      if (this.focusedKey && !next.some(doc => fileKey(doc) === this.focusedKey)) {
        this.focusedKey = next[Math.min(Math.max(0, focusedIndex), next.length - 1)] ? fileKey(next[Math.min(Math.max(0, focusedIndex), next.length - 1)]!) : null;
      }
      this.render();
      if (hadFocus) this.restoreFocus();
    };
    if (this.pressed) this.pending = reconcile;
    else reconcile();
  }

  private render(): void {
    if (this.container.hidden) return;
    const hadFocus = this.container.contains(document.activeElement);
    const start = Math.min(Math.max(0, this.entries.length - 1), Math.max(0, Math.floor(this.container.scrollTop / ROW_HEIGHT) - OVERSCAN));
    const end = Math.min(this.entries.length, start + Math.ceil((this.container.clientHeight || 560) / ROW_HEIGHT) + OVERSCAN * 2);
    this.content.style.height = `${this.entries.length * ROW_HEIGHT}px`;
    const mounted = new Map([...this.content.children].map(row => [row.querySelector<HTMLButtonElement>("button")!.dataset.fileKey!, row as HTMLElement]));
    const rows: HTMLElement[] = [];
    const indices = Array.from({ length: end - start }, (_, index) => start + index);
    const focusedIndex = hadFocus ? this.entries.findIndex(doc => fileKey(doc) === this.focusedKey) : -1;
    if (focusedIndex >= 0 && (focusedIndex < start || focusedIndex >= end)) { indices.push(focusedIndex); indices.sort((a, b) => a - b); }
    for (const index of indices) {
      const doc = this.entries[index]!;
      const existing = mounted.get(fileKey(doc));
      if (existing) {
        existing.style.top = `${index * ROW_HEIGHT}px`;
        existing.setAttribute("aria-posinset", String(index + 1));
        existing.setAttribute("aria-setsize", String(this.entries.length));
        const button = existing.querySelector<HTMLButtonElement>("button")!;
        button.classList.toggle("is-selected", doc.id === this.selectedId);
        button.classList.toggle("is-ignored", doc.gitIgnoreStatus === "ignored");
        if (doc.id === this.selectedId) button.setAttribute("aria-current", "true"); else button.removeAttribute("aria-current");
        button.tabIndex = this.focusedKey ? (this.focusedKey === fileKey(doc) ? 0 : -1) : (index === 0 ? 0 : -1);
        const age = existing.querySelector<HTMLTimeElement>("time")!;
        age.dataset.mtime = String(doc.mtimeMs); age.dateTime = new Date(doc.mtimeMs).toISOString();
        age.title = age.dateTime; age.setAttribute("aria-label", `Last written ${age.dateTime}`);
        age.textContent = relativeWriteAge(doc.mtimeMs);
        const fullPath = this.model.searchPath(doc);
        button.dataset.path = doc.relativePath;
        existing.querySelector<HTMLElement>(".recent-file-name")!.textContent = doc.name;
        existing.querySelector<HTMLElement>(".recent-file-path")!.textContent = fullPath.includes("/") ? fullPath.slice(0, fullPath.lastIndexOf("/")) : ".";
        button.setAttribute("aria-label", `${fullPath}, last written ${age.dateTime}`);
        this.syncRowActions(existing, doc);
        rows.push(existing); continue;
      }
      const row = document.createElement("div");
      row.className = "recent-file";
      row.setAttribute("role", "listitem");
      row.setAttribute("aria-posinset", String(index + 1));
      row.setAttribute("aria-setsize", String(this.entries.length));
      row.style.top = `${index * ROW_HEIGHT}px`;
      const button = document.createElement("button");
      button.type = "button";
      button.dataset.fileKey = fileKey(doc);
      button.dataset.path = doc.relativePath;
      button.className = "recent-file-open";
      button.classList.toggle("is-selected", doc.id === this.selectedId);
      button.classList.toggle("is-ignored", doc.gitIgnoreStatus === "ignored");
      if (doc.id === this.selectedId) button.setAttribute("aria-current", "true");
      button.tabIndex = this.focusedKey ? (this.focusedKey === fileKey(doc) ? 0 : -1) : (index === 0 ? 0 : -1);
      const icon = document.createElement("span");
      icon.className = `recent-file-icon is-${doc.kind}`;
      icon.setAttribute("aria-hidden", "true");
      icon.textContent = /\.(png|jpe?g|gif|svg|webp)$/i.test(doc.name) ? "▧" : doc.kind === "binary" ? "◇" : "▤";
      const labels = document.createElement("span");
      labels.className = "recent-file-labels";
      const name = document.createElement("span"); name.className = "recent-file-name"; name.textContent = doc.name;
      const path = document.createElement("span"); path.className = "recent-file-path";
      const fullPath = this.model.searchPath(doc);
      path.textContent = fullPath.includes("/") ? fullPath.slice(0, fullPath.lastIndexOf("/")) : ".";
      labels.append(name, path);
      const age = document.createElement("time");
      age.dataset.mtime = String(doc.mtimeMs);
      age.dateTime = new Date(doc.mtimeMs).toISOString();
      age.title = age.dateTime;
      age.setAttribute("aria-label", `Last written ${age.dateTime}`);
      age.textContent = relativeWriteAge(doc.mtimeMs);
      button.setAttribute("aria-label", `${fullPath}, last written ${age.dateTime}`);
      button.append(icon, labels, age);
      button.addEventListener("focus", () => { this.focusedKey = fileKey(doc); this.focusedAction = "open"; });
      button.addEventListener("click", () => {
        // A removed pressed file may still be painted, but cannot navigate.
        if (this.model.get(fileKey(doc))) this.onSelect(doc.id);
      });
      row.append(button); this.syncRowActions(row, doc); rows.push(row);
    }
    const wanted = new Set(rows);
    for (const child of [...this.content.children]) if (!wanted.has(child as HTMLElement)) child.remove();
    for (const [index, row] of rows.entries()) if (this.content.children[index] !== row) this.content.insertBefore(row, this.content.children[index] ?? null);
    if (hadFocus) this.restoreFocus();
  }

  private refreshAges(): void {
    for (const age of this.content.querySelectorAll<HTMLTimeElement>("time[data-mtime]")) age.textContent = relativeWriteAge(Number(age.dataset.mtime));
  }
  private restoreFocus(): void {
    const button = [...this.content.querySelectorAll<HTMLButtonElement>(".recent-file-open")].find(el => el.dataset.fileKey === this.focusedKey);
    const target = this.focusedAction === "play" ? button?.parentElement?.querySelector<HTMLButtonElement>(".recent-file-play") ?? button : button;
    if (target) target.focus({ preventScroll: true });
    else this.container.focus({ preventScroll: true });
  }
  private keydown(event: KeyboardEvent): void {
    const current = this.entries.findIndex(doc => fileKey(doc) === this.focusedKey);
    let index: number;
    if (event.key === "ArrowDown") index = Math.min(this.entries.length - 1, current + 1);
    else if (event.key === "ArrowUp") index = Math.max(0, current - 1);
    else if (event.key === "Home") index = 0;
    else if (event.key === "End") index = this.entries.length - 1;
    else return;
    const doc = this.entries[index]; if (!doc) return;
    event.preventDefault(); this.focusedKey = fileKey(doc);
    if (index * ROW_HEIGHT < this.container.scrollTop) this.container.scrollTop = index * ROW_HEIGHT;
    else if ((index + 1) * ROW_HEIGHT > this.container.scrollTop + this.container.clientHeight) this.container.scrollTop = (index + 1) * ROW_HEIGHT - this.container.clientHeight;
    this.render(); this.restoreFocus();
  }
  dispose(): void {
    clearInterval(this.timer); this.observer.disconnect();
    window.removeEventListener("pointerup", this.release);
    window.removeEventListener("pointercancel", this.release);
    window.removeEventListener("blur", this.release);
  }
}
